/** 返回 QQ 系统表情的中文名；未知 id 返回空串。 */
export function faceName(id) {
  const n = Number(id);
  if (!Number.isInteger(n)) return '';
  return NAMES[n] ?? '';
}

/** 给模型看的标签：能认出来就用中文名，认不出就用编号。 */
export function faceLabel(id, fallbackSummary = '') {
  const name = faceName(id) || String(fallbackSummary ?? '').trim();
  return name ? `[表情:${name}]` : `[表情#${id}]`;
}

export const FACE_COUNT = Object.keys(NAMES).length;

/** 名字 → id（支持部分匹配，如「笑」能命中「微笑」「偷笑」里第一个）。 */
export function faceIdByName(name) {
  const q = String(name ?? '').trim();
  if (!q) return null;
  if (/^\d+$/.test(q)) return Number(q);
  const exact = Object.entries(NAMES).find(([, n]) => n === q);
  if (exact) return Number(exact[0]);
  const partial = Object.entries(NAMES).find(([, n]) => n.includes(q) || q.includes(n));
  return partial ? Number(partial[0]) : null;
}

/** 搜索表情名，返回 [{id, name}]，给"想发个笑的表情"这种模糊意图用。 */
export function searchFaces(keyword, limit = 8) {
  const q = String(keyword ?? '').trim();
  if (!q) return [];
  return Object.entries(NAMES)
    .filter(([, n]) => n.includes(q) || q.includes(n))
    .slice(0, limit)
    .map(([id, name]) => ({ id: Number(id), name }));
}