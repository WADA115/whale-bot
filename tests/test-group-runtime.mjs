import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createGroupRuntime } from '../src/group/runtime.js';

let pass = 0;
const ok = (name, cond) => { if (cond) { pass += 1; console.log('  ✅ ' + name); } else { console.log('  ❌ ' + name); process.exitCode = 1; } };
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'group-'));
const rt = createGroupRuntime({ dbPath: path.join(dir, 'group.db'), cfg: { groupRuntime: { botCooldownMs: 30000 }, role: { displayName: '鱼鱼' } } });
const a = rt.observe({ group: 'g1', userId: 'u1', name: '甲', text: '在吗', messageId: 'm1' });
ok('普通消息不直接回', a.decision === 'ignore');
const b = rt.observe({ group: 'g1', userId: 'u2', name: '乙', text: '@鱼鱼 在吗', messageId: 'm2' });
ok('@ 直接回', b.decision === 'direct' && b.target === '乙');
rt.recordBotReply('g1', { messageId: 'm2' });
const c = rt.observe({ group: 'g1', userId: 'u1', name: '甲', text: '继续', messageId: 'm3' });
ok('Bot 冷却内不插话', c.decision === 'ignore' && c.reason === 'bot-cooldown');
rt.rememberImage('g1', { messageId: 'img1', desc: '一张测试图', user: '甲' });
ok('图片引用', rt.lastImage('g1')?.desc === '一张测试图');
const d = rt.observe({ group: 'g1', userId: 'u1', name: '甲', text: ' @鱼鱼 解释上面', messageId: 'm4' });
ok('冷却内 @ 也不刷屏', d.decision === 'ignore' && d.reason === 'direct-cooldown');
rt.recordBotReply('g1', { messageId: 'm2', at: Date.now() - 6000 });
const d2 = rt.observe({ group: 'g1', userId: 'u1', name: '甲', text: ' @鱼鱼 现在呢', messageId: 'm5' });
ok('冷却结束后 @ 恢复', d2.decision === 'direct');
const ownerRt = createGroupRuntime({ dbPath: path.join(dir, 'owner.db'), cfg: { groupRuntime: { ownerReplyProbability: 0.35 }, role: { displayName: '鱼鱼' } }, random: () => 0.9 });
const ownerSkip = ownerRt.observe({ group: 'g2', userId: 'owner', name: '管理员', text: '普通一句', messageId: 'o1', owner: true });
ok('owner 普通发言按概率跳过', ownerSkip.decision === 'ignore' && ownerSkip.reason === 'owner-skip');
const ownerRt2 = createGroupRuntime({ dbPath: path.join(dir, 'owner2.db'), cfg: { groupRuntime: { ownerReplyProbability: 0.35 }, role: { displayName: '鱼鱼' } }, random: () => 0.1 });
const ownerHit = ownerRt2.observe({ group: 'g3', userId: 'owner', name: '管理员', text: '普通一句', messageId: 'o2', owner: true });
ok('owner 概率命中', ownerHit.decision === 'likely' && ownerHit.reason === 'owner-probability');
const ownerMention = ownerRt2.observe({ group: 'g3', userId: 'owner', name: '管理员', text: '@鱼鱼 在吗', messageId: 'o3', owner: true });
ok('owner @ 仍 100%', ownerMention.decision === 'direct');
ownerRt.close(); ownerRt2.close();
rt.close();
fs.rmSync(dir, { recursive: true, force: true });
console.log(`\n${pass} 项群聊运行时测试通过`);
